// Generates src/content/docs/reference/protocol-expressions.mdx from
// src/data/protocol-expressions.json, the expression reference exported from
// Arete's own protocol checker. The tables (functions, operators, names,
// scopes, limits, check codes) come from the JSON; the prose is here.
//
//   node scripts/protocol-expressions.mjs          # write the page
//   node scripts/protocol-expressions.mjs --check  # fail when it is stale
//
// To update the reference, replace the JSON with the checker's new export
// and run this script.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import * as prettier from "prettier";

const DATA = new URL("../src/data/protocol-expressions.json", import.meta.url);
export const PAGE = new URL(
  "../src/content/docs/reference/protocol-expressions.mdx",
  import.meta.url,
);
const SCHEMA = "arete.protocol-expression-reference/v1";

/** Inline code that survives a table cell. */
function code(text) {
  return `\`${String(text).replaceAll("|", "\\|")}\``;
}

/** Plain text for a table cell. */
function cell(text) {
  return String(text).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function table(head, rows) {
  return [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function functionsTable(functions) {
  return table(
    ["Function", "Returns", "What it does", "Example"],
    functions.map((fn) => [
      code(fn.signature),
      cell(fn.returns),
      cell(
        fn.evaluates
          ? fn.summary
          : `${fn.summary} **Checks, but protocol evaluation rejects it**: avoid it in protocols.`,
      ),
      code(fn.example),
    ]),
  );
}

function argsTable(functions) {
  const rows = [];
  for (const fn of functions) {
    for (const arg of fn.args) {
      rows.push([code(fn.name), code(arg.name), cell(arg.type)]);
    }
  }
  return table(["Function", "Argument", "Type"], rows);
}

function operatorsTable(operators) {
  return table(
    ["Operator", "Precedence", "Returns", "Meaning"],
    [
      ...operators.prefix.map((op) => [
        `${code(op.symbol)} (prefix)`,
        String(op.precedence),
        cell(op.returns),
        cell(op.summary),
      ]),
      ...[...operators.binary]
        .sort((a, b) => b.precedence - a.precedence)
        .map((op) => [
          code(op.symbol),
          String(op.precedence),
          cell(op.returns),
          cell(op.summary),
        ]),
    ],
  );
}

function namesTable(names) {
  return table(
    ["Name", "Type", "What it is"],
    names.map((name) => [code(name.name), cell(name.type), cell(name.summary)]),
  );
}

function scopesTable(scopes) {
  const roots = (list) => (list.length === 0 ? "none" : list.map(code).join(", "));
  return table(
    ["Site", "Where", "Always in scope", "When declared", "Notes"],
    scopes.map((scope) => [
      code(scope.site),
      scope.pointers.map(code).join("<br />"),
      roots(scope.roots),
      roots(scope.declaredRoots),
      cell(scope.note),
    ]),
  );
}

function codesTable(codes, stage) {
  return table(
    ["Code", "Cause", "Fix"],
    codes
      .filter((entry) => entry.stage === stage)
      .map((entry) => [code(entry.code), cell(entry.cause), cell(entry.fix)]),
  );
}

export function render(reference) {
  if (reference.schema !== SCHEMA) {
    throw new Error(`expected ${SCHEMA}, found ${reference.schema}`);
  }
  const { limits } = reference;
  return `---
title: Protocol expression reference
description: Every function, operator and name protocol expressions may use, where each name is in scope, the limits, and every check rejection with its fix.
---

{/* Generated by docs/scripts/protocol-expressions.mjs from src/data/protocol-expressions.json. Do not edit by hand. */}

Guards, derived states, reaction triggers, binds, glue, fees and instruction
templates are written as expressions. This page is generated from the
reference that Arete's protocol checker exports, so it lists exactly what an
upload accepts. \`npx arete-protocol check\` runs a local check of syntax and
names. With a secret key, \`npx arete-protocol check\`,
\`a4 protocol deploy --dry-run\` and the MCP tool \`protocol_check\` also run
the server's checks, without uploading anything.

## Values

- **Integers** are written as numbers: \`1000\`, \`-3\`. Protocol integer
  math is exact and fails on overflow or division by zero; there are no
  floats. A float literal such as \`1.5\` parses but fails when evaluated.
- **u64 and larger values** arrive in JSON as decimal strings (an arg with
  \`format: "u64"\` is \`"1500"\`). They are typed as integers, so
  \`args.amount >= 1000\` works, and comparisons are by value.
- **Strings** are JSON strings: \`"vault-"\`, with JSON escapes.
- **Public keys** are base58 strings. A string literal is accepted wherever a
  public key is expected: \`wallet == "So11111111111111111111111111111111111111112"\`.
- **Booleans and null**: \`true\`, \`false\`, \`null\` (also \`none\`).
- **Byte arrays** are written \`[1, 2, 3]\`: integers from 0 to 255, for
  seeds and byte arguments. Brackets build bytes only; they do not index (see
  [Not supported](#not-supported)).

## Operators

All binary operators are left-associative; a higher precedence binds
tighter. Use parentheses to group. Comparisons other than \`==\` and \`!=\`
compare integers.

${operatorsTable(reference.operators)}

## Functions

${reference.functions.length} functions are available in protocols. Arguments
marked \`integer literal\` or \`string literal\` must be written as literals.

${functionsTable(reference.functions)}

${reference.stackSourceOnlyFunctions.map(code).join(", ")} are float math, available in stack
sources but not in protocols.

### Argument types

${argsTable(reference.functions)}

## Names

${namesTable(reference.names)}

## Where each name is in scope

The checker gives each expression the names of the place it sits in. A name
outside its place is an \`unknown-reference\`. "When declared" roots exist only
if the spec declares them: \`args.*\` when the step has args, \`reads.*\` for the
reads the step or machine lists, and so on.

${scopesTable(reference.scopes)}

## Limits

Each expression may be at most ${limits.maxExpressionBytes} bytes, ${limits.maxExpressionNodes}
nodes (literals, names, operators and calls) and ${limits.maxNestingDepth} levels of nesting.
Over a limit, the check answers \`source-limit-exceeded\`.

## Not supported

| Instead of | Write |
| --- | --- |
| \`list[0].field\` (indexing) | \`index(list, 0)\`; the result is untyped, so a field after it is not checked. Brackets only build byte arrays |
| \`args.venue in [...]\` (allow-lists) | \`args.venue == resources.venueA \\|\\| args.venue == resources.venueB\` |
| \`resources.venues[args.venue]\` (keyed lookups) | One resource per entry, chosen with \`if(...)\` or allowed with \`\\|\\|\`, so every address stays reviewable |
| \`cond ? a : b\` | \`if(cond, a, b)\` |
| \`x.len()\`, \`x.startsWith(y)\` (methods) | \`len(x)\`, \`starts_with(x, y)\` |
| \`-x\` on a name | \`0 - x\` (a leading \`-\` is only part of a number literal) |
| Float math (\`1.5 * x\`, \`pow\`) | Scaled integer math: \`x * 15 / 10\` |
| A PDA the program's IDL does not name | Only the IDL's named PDAs: \`pda("alias", "name", seeds...)\` |
| Variables or \`let\` | Repeat the sub-expression, or derive a machine state from it |
| \`x ?? y\` with a non-literal default | A literal default (\`x ?? 0\`), or \`if(exists(x), x, y)\` |

## Rejections

### Upload and activation

An upload (and the server check) answers with a problem whose \`code\` names
the stage and whose \`errors\` list names each failure: \`path\` (a JSON
pointer into the spec), \`code\` and \`message\`.

| Code | When | Fix |
| --- | --- | --- |
| \`protocol-invalid-document\` | The spec does not match the contract schema. \`contractCode\` and \`path\` say where | Rebuild with the current \`@usearete/protocol\`; fix the field at \`path\` |
| \`protocol-spec-check-failed\` | An expression failed its check. Each \`errors\` entry has one of the expression codes below | Fix each entry at its \`path\` |
| \`protocol-template-check-failed\` | A template does not match the program it calls. Each \`errors\` entry has one of the template codes below | Fix each entry at its \`path\` |
| \`protocol-bundle-mismatch\` | A handler step without \`handlers.mjs\`, or a bundle with a template-only spec | Upload exactly the build's files |
| \`protocol-bundle-invalid\`, \`protocol-bundle-too-large\` | The bundle is not canonical base64, or is over the size limit | Upload the build's \`handlers.mjs\` |
| \`protocol-template-check-pending\` | Activation: Arete does not have a program spec a template pins yet. \`errors\` names each one (\`protocol-program-spec-missing\`) | Publish or install the program, then activate again |
| \`protocol-resource-unpublished\` | Activation: a resource the spec declares has no published version. \`errors\` names each one | Publish a value for each resource |
| \`protocol-fee-policy-missing\` | Activation: the deployment's fee policy is missing | Create the deployment with a fee policy |
| \`protocol-review-required\` | Activation of a release with handler code | An operator reviews the release first |
| \`plan-capability-required\` | The account's plan cannot create protocols | See \`a4 auth whoami\` |

### Expression codes

${codesTable(reference.checkCodes, "expression")}

### Template codes

${codesTable(reference.checkCodes, "template")}

### Prepare and submit

Template codes that appear when a step is prepared:

${codesTable(reference.checkCodes, "prepare")}

Other prepare and submit answers:

| Code | When | Fix |
| --- | --- | --- |
| \`guard_rejected\` | A guard was false | The \`guard\` field names it; check the step's preconditions with \`protocol_actions\` |
| \`instance_terminal\`, \`participant_terminal\` | The instance or the wallet's participant has finished | Use another instance |
| \`step_not_client_callable\` | The step is a keeper or admin step | Keepers and operators run it |
| \`step_requires_secret_key\` | The step is secret | Prepare it with a secret-key session |
| \`step_scope_mismatch\` | The step is not prepared on this route (a create step on an instance, say) | Use the route for the step's scope |
| \`protocol-args-invalid\` | The args do not match the step's args schema | Fix the field the message names |
| \`protocol-deployment-inactive\` | The deployment is not active | Activate it |
| \`transaction-entitlement-required\` | The account cannot use the managed transaction gateway | See \`a4 auth whoami\` |
| \`idempotency_key_conflict\` | The idempotency key was used for a different request | Use a new key |
| \`execution_intent_expired\` | The prepared execution expired before submit | Prepare it again |
`;
}

export async function formatted(text) {
  const options = (await prettier.resolveConfig(fileURLToPath(PAGE))) ?? {};
  return prettier.format(text, { ...options, filepath: fileURLToPath(PAGE) });
}

export async function generate() {
  const reference = JSON.parse(await readFile(DATA, "utf8"));
  return formatted(render(reference));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const page = await generate();
  if (process.argv.includes("--check")) {
    const current = await readFile(PAGE, "utf8").catch(() => "");
    if (current !== page) {
      console.error(
        "reference/protocol-expressions.mdx is stale: run node scripts/protocol-expressions.mjs",
      );
      process.exit(1);
    }
  } else {
    await writeFile(PAGE, page);
  }
}
